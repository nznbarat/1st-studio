/* ══════════════════════════════════════════════════════════════════════
   Жижиг markdown хөтөч — дээрх агуулгыг HTML болгоно
   ══════════════════════════════════════════════════════════════════════ */
function mdEsc(t) {
  return String(t).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}
function mdInline(t) {
  return mdEsc(t)
    .replace(/\[\[(.+?)\]\]/g, '<kbd>$1</kbd>')
    .replace(/\*\*(.+?)\*\*/g, '<b>$1</b>')
    .replace(/(^|[^*])\*([^*]+?)\*/g, '$1<em>$2</em>');
}
function mdRow(line) {
  return line.trim().replace(/^\|/, '').replace(/\|$/, '').split('|').map(c => c.trim());
}
function mdToHtml(src) {
  const L = src.replace(/\r/g, '').split('\n');
  let h = '', i = 0;
  const flushPara = buf => buf.length ? '<p>' + mdInline(buf.join(' ')) + '</p>' : '';
  while (i < L.length) {
    const ln = L[i];
    if (!ln.trim()) { i++; continue; }

    if (/^###\s+/.test(ln)) { h += '<div class="mh3">' + mdInline(ln.replace(/^###\s+/, '')) + '</div>'; i++; continue; }
    if (/^##\s+/.test(ln)) { h += '<div class="mh2">' + mdInline(ln.replace(/^##\s+/, '')) + '</div>'; i++; continue; }
    if (/^---+\s*$/.test(ln)) { h += '<hr>'; i++; continue; }

    if (/^\|/.test(ln)) {                                   /* хүснэгт */
      const rows = [];
      while (i < L.length && /^\|/.test(L[i])) { rows.push(L[i]); i++; }
      const body = rows.filter(r => !/^\|[\s:-]+\|?[\s:|-]*$/.test(r));
      h += '<table>';
      body.forEach((r, ri) => {
        const cells = mdRow(r);
        h += '<tr>' + cells.map(c => ri === 0
          ? '<th>' + mdInline(c) + '</th>'
          : '<td>' + mdInline(c) + '</td>').join('') + '</tr>';
      });
      h += '</table>';
      continue;
    }
    if (/^[->!]\s/.test(ln) && (ln[0] === '>' || ln[0] === '!')) {   /* зөвлөгөө / анхааруулга */
      const mark = ln[0], buf = [];
      while (i < L.length && L[i][0] === mark && /^.\s/.test(L[i])) { buf.push(L[i].slice(1).trim()); i++; }
      h += '<div class="note' + (mark === '!' ? ' warnbox' : '') + '">' + mdInline(buf.join(' ')) + '</div>';
      continue;
    }
    if (/^-\s+/.test(ln)) {                                  /* цэгтэй жагсаалт */
      const buf = [];
      while (i < L.length && /^-\s+/.test(L[i])) {
        let item = L[i].replace(/^-\s+/, ''); i++;
        while (i < L.length && /^\s{2,}\S/.test(L[i])) { item += ' ' + L[i].trim(); i++; }
        buf.push(item);
      }
      h += '<ul>' + buf.map(x => '<li>' + mdInline(x) + '</li>').join('') + '</ul>';
      continue;
    }
    if (/^\d+\.\s+/.test(ln)) {                              /* дугаартай жагсаалт */
      const buf = [];
      while (i < L.length && /^\d+\.\s+/.test(L[i])) {
        let item = L[i].replace(/^\d+\.\s+/, ''); i++;
        while (i < L.length && /^\s{2,}\S/.test(L[i])) { item += ' ' + L[i].trim(); i++; }
        buf.push(item);
      }
      h += '<ol>' + buf.map(x => '<li>' + mdInline(x) + '</li>').join('') + '</ol>';
      continue;
    }
    const buf = [];                                          /* энгийн догол мөр */
    while (i < L.length && L[i].trim() && !/^(#{2,3}\s|\||-\s|>\s|!\s|\d+\.\s|---)/.test(L[i])) { buf.push(L[i].trim()); i++; }
    h += flushPara(buf);
  }
  return h;
}

