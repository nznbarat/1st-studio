function manualGo(id) {
  const q = document.getElementById('manQ');
  if (q && q.value) { q.value = ''; manualNav(null); }
  manualRender(id);
}
function manualSearch(q) {
  q = (q || '').trim().toLowerCase();
  if (q.length < 2) { manualNav(null); manualRender(manualCur); return; }
  const hits = {}, out = [];
  MANUAL.forEach(s => {
    const lines = (s.t + '\n' + s.md).split('\n').filter(l => l.toLowerCase().indexOf(q) >= 0);
    if (!lines.length) return;
    hits[s.id] = lines.length;
    out.push({ s: s, lines: lines.slice(0, 6) });
  });
  manualNav(hits);
  const rx = new RegExp('(' + q.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + ')', 'ig');
  let h = '<div class="mh1">🔍 Хайлт: ' + mdEsc(q) + '</div>';
  if (!out.length) h += '<p>Илэрц олдсонгүй. Өөр үгээр хайж үзнэ үү.</p>';
  out.forEach(r => {
    h += '<div class="mh2">' + r.s.ico + '  ' + r.s.t + '</div>';
    r.lines.forEach(l => {
      const clean = mdInline(l.replace(/^[#>!|\-\s]+/, '').replace(/\|/g, ' · '));
      h += '<div class="hit">' + clean.replace(rx, '<mark>$1</mark>') + '</div>';
    });
    h += '<p><button class="w" data-man="' + r.s.id + '">Энэ хэсгийг нээх →</button></p>';
  });
  const el = document.getElementById('mantxt');
  el.innerHTML = h; el.scrollTop = 0;
}
function manualInit() {
  manualNav(null);
  manualRender(manualCur);
}
function openManual() {
  const m = document.getElementById('manual'); if (!m) return;
  const q = document.getElementById('manQ');
  if (q && q.value) { q.value = ''; manualNav(null); }      /* хуучин хайлтыг цэвэрлэнэ */
  m.classList.add('show'); manualOpen = true;
  manualRender(manualCur);
}
function closeManual() {
  const m = document.getElementById('manual'); if (!m) return;
  m.classList.remove('show'); manualOpen = false;
}
